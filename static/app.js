    function _phaseData(p) {
        // Legacy manifest format: nested coarse/fine dicts (pre-slim)
        if (p && p.coarse && p.fine) return p.fine;
        // Slim manifest format: flattened coarse_measurements/fine_measurements
        // For Bayesian 2-phase runs show fine-phase measurement count in comparisons
        if (p && p.fine_measurements != null) return { ...p, measurements: p.fine_measurements };
        return p;
    }
    function _mv(obj, ...keys) {
        if (!obj) return null;
        const m = obj.metrics || {};
        for (const k of keys) {
            if (obj[k] != null) return obj[k];
            if (m[k] != null) return m[k];
        }
        return null;
    }

    function buildSummaryEntities(generator, noise) {
        const noiseSet = new Set(Array.isArray(noise) ? noise : [noise]);
        const all = (window.MANIFEST || []).filter(p =>
            p.generator === generator && noiseSet.has(p.noise) && p.type === 'scan'
        );
        const strategies = [...new Set(all.map(p => p.strategy))].sort();
        const entities = [];
        for (const strategy of strategies) {
            const strategyPlots = all.filter(p => p.strategy === strategy);
            const runs = strategyPlots.map(p => _phaseData(p));
            if (runs.length) {
                entities.push(..._makeStrategyEntities(runs, strategy, true, strategyPlots));
            }
        }
        return entities;
    }

    function _shortStratLabel(strategy) {
        return strategy
            .replace('Bayesian-', '')
            .replace('SimpleSobol', 'Sobol')
            .replace('SimpleSweep', 'Sweep')
            .replace('StagedSobolSweep', 'StagedSobol')
            .replace('GaussianMixture', 'GaussMix');
    }

    function _makeStrategyEntities(d, strategy, isArray, parentPlots) {
        const push = (arr, v) => { if (v != null) arr.push(v); };
        const label = _shortStratLabel(strategy);
        const id = strategy.toLowerCase().replace(/[^a-z0-9]/g, '_');

        if (isArray) {
            const base = {
                id, label,
                steps: [], uncert: [], err: [],
                steps_to_fb: [], uncert_at_fb: [], err_at_fb: [],
                f_spans: [], repeats: [],
                stepsType: 'measurements',
            };
            const freqConv = {
                id: id + '_freq', label: label + ' freq converged',
                steps: [], uncert: [], err: [],
                steps_to_fb: [], uncert_at_fb: [], err_at_fb: [],
                f_spans: [], repeats: [],
                stepsType: 'steps',
            };
            const allConv = {
                id: id + '_conv', label: label + ' converged',
                steps: [], uncert: [], err: [],
                steps_to_fb: [], uncert_at_fb: [], err_at_fb: [],
                f_spans: [], repeats: [],
                stepsType: 'steps',
            };
            for (let i = 0; i < d.length; i++) {
                const item = d[i];
                const p = parentPlots ? parentPlots[i] : null;
                
                let f_span = null;
                if (p && p.true_params && p.true_params.params) {
                    const params = p.true_params.params;
                    const lw = params.linewidth;
                    const split = params.split || 0.0;
                    let domain_width = 5.0e8;
                    if (p.true_params.bounds && p.true_params.bounds.frequency) {
                        const freq_bounds = p.true_params.bounds.frequency;
                        if (freq_bounds.length === 2 && freq_bounds[1] > freq_bounds[0]) {
                            domain_width = freq_bounds[1] - freq_bounds[0];
                        }
                    }
                    if (lw && lw > 0) {
                        f_span = Math.max(2.0 * lw, split + lw) / domain_width;
                    }
                }
                
                const rep = p ? p.repeat : null;

                const base_step = _mv(item, 'measurements');
                if (base_step != null) {
                    base.steps.push(base_step);
                    base.uncert.push(_mv(item, 'uncert'));
                    base.err.push(_mv(item, 'abs_err_x'));
                    base.steps_to_fb.push(_mv(item, 'steps_to_fb', 'freq_converged_step'));
                    base.uncert_at_fb.push(_mv(item, 'uncert_fb_at_milestone'));
                    base.err_at_fb.push(_mv(item, 'err_fb_at_milestone'));
                    base.f_spans.push(f_span);
                    base.repeats.push(rep);
                }

                const freq_step = _mv(item, 'freq_converged_step', 'steps_to_fb');
                if (freq_step != null) {
                    freqConv.steps.push(freq_step);
                    freqConv.uncert.push(_mv(item, 'uncert_fb_at_milestone'));
                    freqConv.err.push(_mv(item, 'err_fb_at_milestone'));
                    freqConv.f_spans.push(f_span);
                    freqConv.repeats.push(rep);
                }

                const all_step = _mv(item, 'all_converged_step');
                if (all_step != null) {
                    allConv.steps.push(all_step);
                    allConv.uncert.push(_mv(item, 'uncert'));
                    allConv.err.push(_mv(item, 'abs_err_x'));
                    allConv.f_spans.push(f_span);
                    allConv.repeats.push(rep);
                }
            }
            const results = [];
            if (base.steps.length) results.push(base);
            if (freqConv.steps.length) results.push(freqConv);
            if (allConv.steps.length) results.push(allConv);
            return results;
        } else {
            const base = {
                id, label,
                steps:        _mv(d, 'measurements'),
                uncert:       _mv(d, 'uncert'),
                err:          _mv(d, 'abs_err_x'),
                steps_to_fb:  _mv(d, 'steps_to_fb', 'freq_converged_step'),
                uncert_at_fb: _mv(d, 'uncert_fb_at_milestone'),
                err_at_fb:    _mv(d, 'err_fb_at_milestone'),
                stepsType: 'measurements',
            };
            const freqStep = _mv(d, 'freq_converged_step', 'steps_to_fb');
            const allStep  = _mv(d, 'all_converged_step');
            const results = [base];
            if (freqStep != null) {
                results.push({
                    id: id + '_freq', label: label + ' freq converged',
                    steps: freqStep,
                    uncert: _mv(d, 'uncert_fb_at_milestone'),
                    err:    _mv(d, 'err_fb_at_milestone'),
                    steps_to_fb: null, uncert_at_fb: null, err_at_fb: null,
                    stepsType: 'steps',
                });
            }
            if (allStep != null) {
                results.push({
                    id: id + '_conv', label: label + ' converged',
                    steps: allStep,
                    uncert: _mv(d, 'uncert'),
                    err:    _mv(d, 'abs_err_x'),
                    steps_to_fb: null, uncert_at_fb: null, err_at_fb: null,
                    stepsType: 'steps',
                });
            }
            return results;
        }
    }

    function buildRepeatEntities(plot) {
        if (!window.MANIFEST) return [];
        const group = window.MANIFEST.filter(p =>
            p.type === 'scan' &&
            p.generator === plot.generator &&
            p.noise === plot.noise &&
            p.repeat === plot.repeat
        );

        const strategies = [...new Set(group.map(p => p.strategy))].sort();
        const entities = [];
        for (const strategy of strategies) {
            const p = group.find(q => q.strategy === strategy);
            if (p) entities.push(..._makeStrategyEntities(_phaseData(p), strategy, false));
        }
        return entities;
    }

    // ── Pairwise metric rows ──────────────────────────────────────────────────
    function buildPairwiseRows(eA, eB) {
        const isArr = v => Array.isArray(v);
        const has = v => isArr(v) ? v.length > 0 : v != null;
        const sub = (a, b) => {
            if (!has(a) || !has(b)) return null;
            if (isArr(a) && isArr(b)) {
                const n = Math.min(a.length, b.length);
                return Array.from({length: n}, (_, i) => b[i] - a[i]);
            }
            return (!isArr(a) && !isArr(b)) ? b - a : null;
        };
        // Δ card header — use the full entity labels. CSS (text-overflow:
        // ellipsis) handles any overflow at render time based on the card's
        // actual width, instead of hard-clipping in JS.
        const deltaLabel = `Δ  ${eB.label} − ${eA.label}`;
        const rows = [];
        const addRow = (metric, aVal, bVal, cA, cB, cD, type) => {
            // Every metric should be present for every entity by construction
            // (the backend captures both "at convergence" and "final" snapshots).
            // If you see a row skipped here, it means the backend data-capture
            // gap has reappeared — investigate rather than hide.
            if (!has(aVal) || !has(bVal)) return;
            rows.push({ label: metric, cards: [
                { label: eA.label, sublabel: metric, data: aVal, color: cA, type },
                { label: eB.label, sublabel: metric, data: bVal, color: cB, type },
                { label: deltaLabel, data: sub(aVal, bVal), color: cD, type },
            ]});
        };
        addRow('Steps to completion',       eA.steps,        eB.steps,        '#f472b6','#60a5fa','#22c55e', eA.stepsType || 'measurements');
        addRow('Final frequency uncertainty',eA.uncert,       eB.uncert,       '#a78bfa','#34d399','#f59e0b','frequency');
        addRow('Final frequency error',      eA.err,          eB.err,          '#c084fc','#10b981','#6366f1','frequency');
        addRow('Steps to freq. convergence', eA.steps_to_fb,  eB.steps_to_fb,  '#fb923c','#38bdf8','#a3e635','steps');
        addRow('Uncertainty @ freq. conv.',  eA.uncert_at_fb, eB.uncert_at_fb, '#818cf8','#2dd4bf','#fbbf24','frequency');
        addRow('Error @ freq. conv.',        eA.err_at_fb,    eB.err_at_fb,    '#d946ef','#4ade80','#f43f5e','frequency');
        return rows;
    }

    // ── Shared selector + card renderer ──────────────────────────────────────
    function entityCriterion(id) {
        // Entity ids end in '_freq' (freq converged) or '_conv' (all converged);
        // no suffix means the full run.
        if (id.endsWith('_freq')) return 'freq';
        if (id.endsWith('_conv')) return 'conv';
        return 'full';
    }

    function buildTwoDropdownSelector(entities, onPairChange, defaultAId, defaultBId) {
        const wrapper = document.createElement('div');
        wrapper.className = 'control-row';
        wrapper.style.cssText = 'gap:0.5em;margin:0.5em 0 0.75em;flex-wrap:wrap;align-items:center;';
        const lbl = document.createElement('span');
        lbl.className = 'control-label';
        lbl.textContent = 'Compare:';
        const selA = document.createElement('select');
        selA.className = 'control-select';
        const vs = document.createElement('span');
        vs.style.cssText = 'padding:0 0.3em;color:#64748b;font-size:0.9em;';
        vs.textContent = 'with';
        const selB = document.createElement('select');
        selB.className = 'control-select';
        const hint = document.createElement('span');
        hint.style.cssText = 'color:#94a3b8;font-size:0.78em;';
        hint.textContent = 'Only pairs with the same stopping criterion are comparable.';
        for (const e of entities) {
            const opt = document.createElement('option');
            opt.value = e.id;
            opt.textContent = e.label;
            selA.appendChild(opt);
        }
        // B only ever offers entities with the same stopping criterion as A:
        // cross-criterion pairs vary both quality and cost at once and answer
        // neither question, so they are not offered at all.
        const refreshBOptions = () => {
            const crit = entityCriterion(selA.value || '');
            const prev = selB.value;
            selB.innerHTML = '';
            const candidates = entities.filter(e => e.id !== selA.value && entityCriterion(e.id) === crit);
            for (const e of candidates) {
                const opt = document.createElement('option');
                opt.value = e.id;
                opt.textContent = e.label;
                selB.appendChild(opt);
            }
            if (candidates.some(e => e.id === prev)) selB.value = prev;
            selB.disabled = candidates.length === 0;
        };
        if (defaultAId) { const i = entities.findIndex(e => e.id === defaultAId); if (i >= 0) selA.selectedIndex = i; }
        refreshBOptions();
        if (defaultBId && entityCriterion(defaultBId) === entityCriterion(selA.value || '') && defaultBId !== selA.value) {
            selB.value = defaultBId;
        }
        const notify = () => {
            const eA = entities.find(e => e.id === selA.value);
            const eB = entities.find(e => e.id === selB.value);
            if (eA && eB) onPairChange(eA, eB);
        };
        selA.addEventListener('change', () => { refreshBOptions(); notify(); });
        selB.addEventListener('change', notify);
        wrapper.appendChild(lbl);
        wrapper.appendChild(selA);
        wrapper.appendChild(vs);
        wrapper.appendChild(selB);
        wrapper.appendChild(hint);
        return { wrapper, notify };
    }

    function renderPairwiseCards(rows, container, isSummary) {
        container.innerHTML = '';
        if (!rows || !rows.length) {
            const p = document.createElement('p');
            p.style.cssText = 'color:#94a3b8;padding:1em 0;font-size:0.9em;';
            p.textContent = 'No shared metrics for this pair.';
            container.appendChild(p);
            return;
        }
        for (const row of rows) {
            const hdr = document.createElement('div');
            hdr.style.cssText = 'margin-top:1em;margin-bottom:0.4em;font-weight:600;color:#334155;font-size:0.85em;';
            hdr.textContent = row.label;
            container.appendChild(hdr);
            const rowDiv = document.createElement('div');
            rowDiv.className = 'scan-metrics-panel' + (isSummary ? ' summary-grid' : '');
            rowDiv.style.marginBottom = '0.75em';
            container.appendChild(rowDiv);
            for (const card of row.cards) {
                const cardDiv = document.createElement('div');
                cardDiv.className = 'metric-item';
                rowDiv.appendChild(cardDiv);
                const lblDiv = document.createElement('div');
                lblDiv.className = 'metric-label';
                // For entity cards (not the Δ card) show the metric as secondary text
                // so it's always clear what's being shown even when scrolling past the heading
                if (card.sublabel) {
                    lblDiv.title = `${card.label} — ${card.sublabel}`;
                }
                lblDiv.textContent = card.label;
                cardDiv.appendChild(lblDiv);
                if (isSummary) {
                    createCardHistogram(cardDiv, card.data, card.label, card.color, card.type);
                } else {
                    const valEl = document.createElement('div');
                    valEl.className = 'metric-value';
                    const v = card.data;
                    if (v == null) { valEl.textContent = 'N/A'; valEl.style.color = '#94a3b8'; }
                    else if (card.type === 'frequency') valEl.textContent = formatFrequency(v);
                    else valEl.textContent = formatCount(v);
                    cardDiv.appendChild(valEl);
                }
            }
        }
    }

    function updateStoppingCriteriaVisibility(plot) {
        // Don't override the row when noise view is active — it has its own logic
        const activeMode = document.querySelector('#scan-view-mode button.is-active');
        if (activeMode && activeMode.dataset.value === 'noise') return;

        const row = document.getElementById('stopping-criteria-row');
        if (!row) return;
        const d = plot ? _phaseData(plot) : null;
        const hasFreq = d && (_mv(d, 'freq_converged_step') != null || _mv(d, 'steps_to_fb') != null);
        const hasAll  = d && _mv(d, 'all_converged_step') != null;
        row.style.display = (hasFreq || hasAll) ? '' : 'none';
        // Disable individual buttons if the data isn't available
        const btns = row.querySelectorAll('button[data-value]');
        for (const btn of btns) {
            const v = btn.dataset.value;
            if (v === 'freq_converged') btn.disabled = !hasFreq;
            else if (v === 'all_converged') btn.disabled = !hasAll;
            else btn.disabled = false;
        }
        // If current criteria is now unavailable, reset to 'full'
        if ((currentStoppingCriteria === 'freq_converged' && !hasFreq) ||
            (currentStoppingCriteria === 'all_converged' && !hasAll)) {
            setStoppingCriteria('full');
        }
    }

